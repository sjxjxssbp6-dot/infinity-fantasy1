package cupcake.nikky.imperium.tower.item.modifier;

public enum ModifierType {
    /**
     * База предмета - атрибуты, что считаются для определнного уровня
     */
    BASE,
    /**
     * Модификаторы типа префикса и суффикса
     */
    EXTENDED,
    /**
     * Модификаторы, которые были добавлены через специального НПС
     */
    CRAFTED,
    /**
     * Дополнительный модификатор внутренней направленности (скрытый модификатор)
     */
    DIRECTION,
    /**
     * Искаженный модификатор, получается путем использования специального предмета
     */
    DISTORTED

}
